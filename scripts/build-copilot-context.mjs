// Builds the assistant's grounding from src/content (plan.md 7.7) and writes it to
// api/_generated/context.ts, which the API function imports. Run by `npm run build`;
// a unit test fails when the committed file is stale.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runnerImport } from "vite";

const src = fileURLToPath(new URL("../src", import.meta.url));
const { module } = await runnerImport("./src/assistant/context.ts", {
  configFile: false,
  logLevel: "error",
  resolve: { alias: { "@": src } },
});

const chunks = module.buildChunks();
const suggestions = module.buildSuggestions();
// Same recipe as the staleness test in src/assistant/context.test.ts.
const version = createHash("sha256")
  .update(JSON.stringify({ chunks, suggestions }))
  .digest("hex")
  .slice(0, 12);

const out = `// Generated by scripts/build-copilot-context.mjs from src/content. Do not edit.
export const CONTEXT = ${JSON.stringify({ version, chunks, suggestions }, null, 2)} as const;
`;
writeFileSync(fileURLToPath(new URL("../api/_generated/context.ts", import.meta.url)), out);
console.log(
  `assistant context ${version}: ${chunks.length} chunks, ${suggestions.length} suggestions`,
);
